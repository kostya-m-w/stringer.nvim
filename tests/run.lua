local s = require('stringer')
local codec = require('stringer.codec')
local store = require('stringer.store')
local state = require('stringer.state')
local pane = require('stringer.pane')
local uv = vim.uv or vim.loop
local cwd = vim.fn.getcwd()
local root = vim.fn.tempname()
vim.fn.mkdir(root, 'p')
root = assert(uv.fs_realpath(root))
local passed, failed = 0, 0
local dir, file, other
local messages = {}
vim.notify = function(message) messages[#messages + 1] = message end

local function eq(a, b)
  assert(vim.deep_equal(a, b), ('expected %s, got %s'):format(vim.inspect(b), vim.inspect(a)))
end
local function yes(ok, err) assert(ok, tostring(err)); return ok end
local function no(ok, err) assert(not ok, 'Expected failure: ' .. tostring(err)) end
local function edit(path, line)
  local buf = vim.fn.bufadd(path)
  vim.fn.bufload(buf)
  vim.api.nvim_set_current_buf(buf)
  vim.api.nvim_win_set_cursor(0, { line or 1, 0 })
end
local function reset()
  vim.o.hidden = true
  vim.cmd('silent! tabonly!')
  vim.cmd('silent! only!')
  vim.cmd('enew!')
  for _, buf in ipairs(vim.api.nvim_list_bufs()) do
    if buf ~= vim.api.nvim_get_current_buf() then vim.api.nvim_buf_delete(buf, { force = true }) end
  end
  state.active, state.windows = nil, {}
  pane.buffers, pane.windows = {}, {}
  vim.api.nvim_set_current_dir(cwd)
  dir = root .. '/' .. (passed + failed + 1)
  vim.fn.mkdir(dir .. '/repo-a', 'p')
  vim.fn.mkdir(dir .. '/repo-b', 'p')
  file, other = dir .. '/repo-a/a "quoted" file.lua', dir .. '/repo-b/b.lua'
  vim.fn.writefile({ 'one', 'two', 'three', 'four' }, file)
  vim.fn.writefile({ 'alpha', 'beta', 'gamma' }, other)
  s.setup({ storage_dir = dir .. '/paths', pane_width = 48 })
  messages = {}
end
local function test(name, fn)
  local ok, err = xpcall(function() reset(); fn() end, debug.traceback)
  if ok then passed = passed + 1; print('PASS ' .. name)
  else failed = failed + 1; print('FAIL ' .. name .. '\n' .. err) end
end
local function capture()
  yes(s.new('demo'))
  edit(file, 2); yes(s.add())
  edit(other, 3); yes(s.add())
  edit(file, 4); yes(s.add())
  return state.active
end
local function rows(record)
  return vim.api.nvim_buf_get_lines(pane.buffer(record), 0, -1, false)
end

test('version 1 format round trips escaped paths and duplicates', function()
  local marks = { { file = file, line = 2 }, { file = file, line = 2 } }
  eq(codec.decode(codec.lines(codec.text(codec.encode(marks)))), marks)
  eq(codec.decode(codec.encode({})), {})
end)
test('invalid records and versions report their exact line numbers', function()
  local marks, errors = codec.decode({ '{"type":"stringer","format_version":2,"mark_version":1}', '',
    '{"file":"relative","line":1}', '{"file":"/a","line":1.5}', 'null', '[]',
    '{"file":"/a","line":1,"extra":true}' })
  eq(marks, nil); eq(#errors, 7)
  for i, err in ipairs(errors) do eq(err.line, i) end
  no(codec.decode(codec.lines(codec.text(codec.encode({})) .. '\n')))
end)
test('storage lists paths and rejects invalid names and duplicate creation', function()
  eq(store.list(), {})
  yes(store.create('z')); yes(store.create('a'))
  eq(store.list(), { 'a', 'z' })
  no(store.create('../bad')); no(store.create('z'))
end)
test('commands complete and reject unexpected arguments', function()
  vim.cmd('Stringer new demo')
  eq(vim.fn.getcompletion('Stringer op', 'cmdline'), { 'open' })
  eq(vim.fn.getcompletion('Stringer open d', 'cmdline'), { 'demo' })
  eq(vim.fn.getcompletion('Stringer move-', 'cmdline'), { 'move-up', 'move-down' })
  vim.cmd('Stringer next unexpected')
  assert(messages[#messages]:find('Usage'))
end)
test('nearest-line selection updates on cursor and file changes', function()
  local r = capture()
  eq(r.index, 3)
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  vim.api.nvim_exec_autocmds('CursorMoved', {})
  eq(r.index, 1)
  edit(other, 1); s.sync(); eq(r.index, 2)
  vim.cmd('enew'); s.sync(); eq(r.index, 2)
end)
test('ties keep the active mark, otherwise choose earlier codepath entry', function()
  local r = capture()
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  s.sync(); eq(r.index, 3)
  r.index = 2; s.sync(); eq(r.index, 1)
end)
test('next and previous cycle using the nearest current location', function()
  local r = capture()
  yes(s.next()); eq(r.index, 1); eq(vim.api.nvim_win_get_cursor(0)[1], 2)
  yes(s.prev()); eq(r.index, 3)
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  yes(s.next()); eq(r.index, 2); eq(vim.api.nvim_buf_get_name(0), other)
end)
test('empty, single-mark, and no-current-mark navigation', function()
  no(s.next()); yes(s.new('demo')); no(s.next())
  edit(file); yes(s.add()); yes(s.next()); yes(s.prev()); eq(state.active.index, 1)
  vim.cmd('enew'); state.active.index = nil
  yes(s.prev()); eq(state.active.index, 1)
end)
test('identical locations remain independently navigable', function()
  yes(s.new('demo')); edit(file, 2); yes(s.add()); yes(s.add())
  yes(s.next()); eq(state.active.index, 2)
  s.sync(); eq(state.active.index, 2)
  yes(s.next()); eq(state.active.index, 1)
end)
test('capture rejects unnamed, unsaved and pane buffers', function()
  yes(s.new('demo')); no(s.add())
  vim.api.nvim_buf_set_name(0, dir .. '/unsaved.lua'); no(s.add())
  yes(s.show()); no(s.add()); eq(#state.active.marks, 0)
end)
test('pane is noneditable and navigation preserves the code window', function()
  local r = capture()
  local codewin = vim.api.nvim_get_current_win()
  yes(s.show())
  local win, buf = vim.api.nvim_get_current_win(), pane.buffer(r)
  eq(vim.bo[buf].modifiable, false); eq(vim.bo[buf].buftype, 'nofile')
  no(pcall(vim.api.nvim_buf_set_lines, buf, 0, 1, false, { 'bad' }))
  yes(s.jump(1)); eq(vim.api.nvim_get_current_win(), codewin)
  eq(vim.api.nvim_win_get_buf(win), buf)
  local marks = vim.api.nvim_buf_get_extmarks(buf, pane.namespace, 0, -1, {})
  eq(#marks, 1); eq(marks[1][2], pane.first_mark_line - 1)
end)
test('moving marks saves immediately and preserves active entry identity', function()
  local r = capture(); yes(s.jump(1)); yes(s.show())
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  yes(s.move_down()); eq(r.index, 2); eq(r.marks[2].line, 2)
  eq(vim.api.nvim_win_get_cursor(0)[1], 4)
  eq(store.load('demo').marks, r.marks)
  yes(s.move_up()); eq(r.index, 1)
  no(s.move_up(1)); no(s.move_down(3))
end)
test('remove and undo persist, including deleting the last remaining mark', function()
  local r = capture(); yes(s.jump(1)); yes(s.show())
  yes(s.remove(1)); eq(r.index, nil); eq(#r.marks, 2)
  yes(s.undo()); eq(r.index, 1); eq(#r.marks, 3)
  eq(store.load('demo').marks, r.marks)
  yes(s.remove(3)); yes(s.remove(2)); yes(s.remove(1))
  eq(#store.load('demo').marks, 0); no(s.next())
  yes(s.undo()); eq(#store.load('demo').marks, 1)
end)
test('pane header actions do not remove an active mark accidentally', function()
  local r = capture(); yes(s.show())
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  no(s.remove()); no(s.move_down()); eq(#r.marks, 3)
end)
test('failed persistence preserves disk, model, history and view', function()
  local r = capture(); yes(s.show())
  local text, view, history = r.text, rows(r), #r.history
  local original = uv.fs_rename
  uv.fs_rename = function() return nil, 'injected failure' end
  local ok, err = pcall(function()
    no(s.remove(1)); no(s.move_down(1)); no(s.undo())
    eq(r.text, text); eq(store.read(r.file), text); eq(rows(r), view); eq(#r.history, history)
    eq(#vim.fn.glob(r.file .. '.*', false, true), 0)
  end)
  uv.fs_rename = original; yes(ok, err)
end)
test('external edits block mutations until reload and clear undo history', function()
  local r = capture()
  local replacement = { { file = other, line = 1 } }
  vim.fn.writefile(codec.encode(replacement), r.file)
  no(s.add()); no(s.remove(1)); no(s.rename('renamed')); no(s.undo())
  yes(s.reload()); eq(state.active.marks, replacement); no(s.undo())
end)
test('invalid external file load preserves current valid state', function()
  local r = capture()
  vim.fn.writefile({ 'invalid' }, r.file)
  no(s.reload()); eq(state.active, r)
  no(s.open('missing')); eq(state.active, r)
end)
test('raw file drafts are protected from mutations and activation', function()
  local r = capture()
  edit(r.file); vim.api.nvim_buf_set_lines(0, 1, 2, false, { 'draft' })
  no(s.remove(1)); no(s.open('demo')); no(s.rename('renamed'))
  eq(vim.api.nvim_buf_get_lines(0, 1, 2, false), { 'draft' })
