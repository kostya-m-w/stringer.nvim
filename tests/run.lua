test('rename updates storage, pane and future writes without changing marks', function()
  local r = capture(); yes(s.show())
  local old, buf, index = r.file, pane.buffer(r), r.index
  yes(s.rename('renamed')); eq(store.read(old), nil)
  eq(r.name, 'renamed'); eq(r.index, index); eq(pane.buffer(r), buf)
  assert(rows(r)[1]:find('renamed'))
  yes(s.remove(1)); eq(store.load('renamed').marks, r.marks)
  yes(s.undo()); eq(#store.load('renamed').marks, 3)
end)
test('rename rejects duplicates and invalid names', function()
  local r = capture(); yes(store.create('taken'))
  no(s.rename('taken')); no(s.rename('../bad'))
  eq(r.name, 'demo'); eq(#store.load('taken').marks, 0)
  yes(s.rename('demo')); eq(#store.load('demo').marks, 3)
end)
test('rename rolls back the new name if removing old name fails', function()
  local r = capture()
  local original = uv.fs_unlink
  uv.fs_unlink = function(path)
    if path == r.file then return nil, 'injected unlink failure' end
    return original(path)
  end
  local ok, err = pcall(function()
    no(s.rename('renamed')); eq(r.name, 'demo')
    eq(store.list(), { 'demo' }); eq(store.read(r.file), r.text)
  end)
  uv.fs_unlink = original; yes(ok, err)
end)
test('empty picker prompts to create and cancellation is harmless', function()
  local original = vim.ui.input
  local ok, err = pcall(function()
    vim.ui.input = function(_, callback) callback(nil) end
    yes(s.open()); eq(state.active, nil); eq(store.list(), {})
    vim.ui.input = function(_, callback) callback('created') end
    yes(s.open()); eq(state.active.name, 'created')
  end)
  vim.ui.input = original; yes(ok, err)
end)
test('picker selection and asynchronous rename target the correct path', function()
  yes(s.new('a')); yes(s.new('b'))
  local original_select, original_input = vim.ui.select, vim.ui.input
  local ok, err = pcall(function()
    vim.ui.select = function(items, _, cb) eq(items, { 'a', 'b' }); cb('a') end
    yes(s.open()); eq(state.active.name, 'a')
    local callback
    vim.ui.input = function(_, cb) callback = cb end
    yes(s.rename()); yes(s.open('b')); callback('wrong')
    eq(store.list(), { 'a', 'b' })
  end)
  vim.ui.select, vim.ui.input = original_select, original_input; yes(ok, err)
end)
